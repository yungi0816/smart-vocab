function normalizeSpace(value) {
  return String(value || '').replace(/\s+/g, ' ').trim();
}

function normalizeTopikSpell(rawSpell) {
  let spell = normalizeSpace(rawSpell);
  if (!spell) {
    return '';
  }

  spell = spell.split('/')[0].trim();
  spell = spell.split(/[∙‧·・]/)[0].trim();

  for (const label of WORD_CLASS_LABELS) {
    spell = spell.replace(new RegExp(`\\s+${label}$`), '').trim();
  }

  if (/^[가-힣\s-]+$/.test(spell)) {
    spell = spell.replace(/\s+/g, '');
  }

  return spell.replace(/[0-9]+$/g, '').trim();
}

function getTopikMeaningOverride(entry) {
  const dayIndex = normalizeSpace(entry.dayIndex);
  const theme = normalizeSpace(entry.theme);
  const spell = normalizeTopikSpell(entry.spell);

  const candidates = [
    `${dayIndex}::${theme}::${spell}`,
    `${theme}::${spell}`,
    `${dayIndex}::${spell}`,
    spell,
  ];

  for (const key of candidates) {
    if (Object.prototype.hasOwnProperty.call(TOPIK_MEANING_OVERRIDES, key)) {
      return TOPIK_MEANING_OVERRIDES[key];
    }
  }

  return null;
}

