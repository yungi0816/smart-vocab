const entries = [];
let mapped = 0;
let unmapped = 0;

for (const [dayKey, dayObj] of Object.entries(data)) {
  const theme = themeJp[dayObj.theme] || dayObj.theme;
  for (const [spell, korMeaning] of Object.entries(dayObj.words)) {
    const jpMeaning = meaningJp[korMeaning];
    if (jpMeaning) {
      entries.push({ lang: 'ENG_JP', theme, day: dayKey, spell, meaning: jpMeaning });
      mapped++;
    } else {
      // 매핑 안 되면 한국어 뜻에 (韓) 표시 — fallback
      entries.push({ lang: 'ENG_JP', theme, day: dayKey, spell, meaning: `${korMeaning}` });
      unmapped++;
      console.warn(`  매핑 없음: ${spell} → ${korMeaning}`);
    }
  }
}

insertMany(entries);

console.log(`\n총 ${entries.length}개 단어 적재 완료`);
console.log(`  - 일본어 매핑: ${mapped}개`);
console.log(`  - 미매핑 (한국어 fallback): ${unmapped}개`);

